-- ==============================================================================
-- Streaming E-Commerce Platform - Snowflake Cloud Warehouse Setup DDL
-- Sets up roles, virtual warehouse, external S3 stages, Snowpipe & dimensional marts.
-- ==============================================================================

USE ROLE ACCOUNTADMIN;

-- 1. Create Virtual Warehouse and Database
CREATE WAREHOUSE IF NOT EXISTS ECOMMERCE_WH
    WITH WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 120
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS ECOMMERCE_DW;
USE DATABASE ECOMMERCE_DW;

CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS STAGING;
CREATE SCHEMA IF NOT EXISTS MARTS;

-- 2. External Stage for S3 Data Lake
CREATE OR REPLACE STAGE RAW.S3_ECOMMERCE_LAKE
    URL = 's3://ecommerce-lake/'
    FILE_FORMAT = (TYPE = 'PARQUET');

-- 3. Staging Tables with Parquet Schema
CREATE OR REPLACE TABLE RAW.STG_ORDERS (
    ORDER_ID VARCHAR(64),
    SESSION_ID VARCHAR(64),
    CUSTOMER_ID VARCHAR(64),
    PRODUCT_ID VARCHAR(64),
    QUANTITY INT,
    UNIT_PRICE NUMBER(10, 2),
    TOTAL_AMOUNT NUMBER(10, 2),
    ORDER_STATUS VARCHAR(32),
    ORDER_TIMESTAMP TIMESTAMP_NTZ,
    ORDER_DATE DATE,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE RAW.STG_CLICKSTREAM (
    EVENT_ID VARCHAR(64),
    SESSION_ID VARCHAR(64),
    CUSTOMER_ID VARCHAR(64),
    PRODUCT_ID VARCHAR(64),
    EVENT_TYPE VARCHAR(32),
    PAGE_URL VARCHAR,
    REFERRER VARCHAR,
    DEVICE VARCHAR(32),
    EVENT_TIMESTAMP TIMESTAMP_NTZ,
    EVENT_DATE DATE,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- 4. Snowpipe for Continuous Loading from S3 Silver Parquet
CREATE OR REPLACE PIPE RAW.PIPE_ORDERS
AUTO_INGEST = TRUE
AS
COPY INTO RAW.STG_ORDERS
FROM (
    SELECT 
        $1:order_id::VARCHAR,
        $1:session_id::VARCHAR,
        $1:customer_id::VARCHAR,
        $1:product_id::VARCHAR,
        $1:quantity::INT,
        $1:unit_price::NUMBER(10, 2),
        $1:total_amount::NUMBER(10, 2),
        $1:order_status::VARCHAR,
        $1:order_timestamp::TIMESTAMP_NTZ,
        $1:order_date::DATE,
        CURRENT_TIMESTAMP()
    FROM @RAW.S3_ECOMMERCE_LAKE/silver/orders/
);

-- 5. Star Schema Mart Tables
CREATE OR REPLACE TABLE MARTS.DIM_CUSTOMERS (
    CUSTOMER_KEY INT AUTOINCREMENT PRIMARY KEY,
    CUSTOMER_ID VARCHAR(64) UNIQUE,
    NAME VARCHAR(128),
    EMAIL VARCHAR(128),
    CITY VARCHAR(64),
    STATE VARCHAR(32),
    COUNTRY VARCHAR(32),
    SIGNUP_DATE DATE
);

CREATE OR REPLACE TABLE MARTS.DIM_PRODUCTS (
    PRODUCT_KEY INT AUTOINCREMENT PRIMARY KEY,
    PRODUCT_ID VARCHAR(64) UNIQUE,
    NAME VARCHAR(128),
    CATEGORY VARCHAR(64),
    PRICE NUMBER(10, 2)
);

CREATE OR REPLACE TABLE MARTS.DIM_DATE (
    DATE_KEY INT PRIMARY KEY,
    DATE DATE UNIQUE,
    DAY_OF_MONTH INT,
    MONTH INT,
    MONTH_NAME VARCHAR(16),
    QUARTER INT,
    YEAR INT,
    DAY_OF_WEEK INT,
    DAY_NAME VARCHAR(16),
    IS_WEEKEND BOOLEAN
);

CREATE OR REPLACE TABLE MARTS.FCT_ORDERS (
    ORDER_ID VARCHAR(64) PRIMARY KEY,
    CUSTOMER_KEY INT FOREIGN KEY REFERENCES MARTS.DIM_CUSTOMERS(CUSTOMER_KEY),
    PRODUCT_KEY INT FOREIGN KEY REFERENCES MARTS.DIM_PRODUCTS(PRODUCT_KEY),
    DATE_KEY INT FOREIGN KEY REFERENCES MARTS.DIM_DATE(DATE_KEY),
    QUANTITY INT,
    REVENUE NUMBER(10, 2),
    ORDER_STATUS VARCHAR(32),
    ORDER_TIMESTAMP TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE MARTS.FCT_CLICKSTREAM (
    EVENT_ID VARCHAR(64) PRIMARY KEY,
    CUSTOMER_KEY INT FOREIGN KEY REFERENCES MARTS.DIM_CUSTOMERS(CUSTOMER_KEY),
    PRODUCT_KEY INT FOREIGN KEY REFERENCES MARTS.DIM_PRODUCTS(PRODUCT_KEY),
    DATE_KEY INT FOREIGN KEY REFERENCES MARTS.DIM_DATE(DATE_KEY),
    EVENT_TYPE VARCHAR(32),
    SESSION_ID VARCHAR(64),
    DEVICE VARCHAR(32),
    REFERRER VARCHAR,
    EVENT_TIMESTAMP TIMESTAMP_NTZ
);
